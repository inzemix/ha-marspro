#!/usr/bin/env python3
"""Dimensional audit of a Mars Pro device report - standard library only.

Why this exists
---------------
An entity that is healthy is not an entity whose value is true. The integration
shipped `outlet.aRms` mapped straight to amps for weeks: the entity was
available, updating, and reporting 103 A where the appliance drew 1.03 A
(24 kW on a socket). Presence, liveness and "0 unavailable" cannot catch that -
only a second, independent physical quantity in the same frame can.

So this script takes the report produced by `marspro.generate_device_report`
(or any report pasted into an issue) and cross-checks every numeric field for
which a relationship exists:

  * outlet:  P / (V x I) = power factor, with I = aRms / 100  -> 0.3 .. 1.0
  * VPD:     recomputed from temperature and humidity            -> +/-0.05 kPa
  * energy:  magnitude (Wh -> kWh) versus a plausible lifetime total
  * CO2, PPFD, soil temperature/humidity/EC: physical magnitudes

Numeric fields with no rule are listed as "no rule", never silently passed.

Usage
-----
    python3 audit_units.py marspro_device_report.txt
    python3 audit_units.py report.txt --verbose

Exit code is 0 when every check passes, 1 otherwise - so it can gate a release
or a support answer.

Keep in sync with the integration
---------------------------------
The conversions here mirror `custom_components/marspro/`:
  * `aRms` is reported in centiamps, so it is divided by 100 (const.py:
    MAX_PLAUSIBLE_A_RAW documents how the factor was derived).
  * `energy` is reported in Wh and exposed in kWh.
  * `vRms` is volts, `wattP` is watts, no scaling.
If a conversion changes in the integration, change it here too.
"""
import argparse
import json
import math
import sys

# --- Conversions mirrored from the integration -------------------------------
A_RMS_DIVISOR = 100.0          # centiamps -> amps
ENERGY_DIVISOR = 1000.0        # Wh -> kWh
MAX_PLAUSIBLE_A = 100.0        # after scaling; beyond that we report unknown
MIN_PF, MAX_PF = 0.30, 1.00    # a real appliance under load never sits outside this
VPD_TOLERANCE = 0.05           # kPa; the device rounds to 2 decimals
# Below these thresholds the power factor is dominated by measurement
# quantisation (wattP is a whole watt, aRms a hundredth of an amp), so a ratio
# there is noise, not evidence. Skipping it is the honest choice - it is what
# keeps a 3 W standby frame from being reported as a bug.
PF_MIN_POWER_W = 20.0
PF_MIN_CURRENT_A = 0.10

# Plausible ranges for values that have no arithmetic relationship to check.
MAGNITUDE_RULES = {
    "co2": (300.0, 5000.0, "ppm"),
    "ppfd": (0.0, 3000.0, "umol/m2/s"),
    "tempSoil": (-10.0, 50.0, "C"),
    "humiSoil": (0.0, 100.0, "%"),
    "ECSoil": (0.0, 20.0, "mS/cm"),
    "temp": (-10.0, 60.0, "C"),
    "humi": (0.0, 100.0, "%"),
    "vpd": (0.0, 10.0, "kPa"),
}

# Fields consumed by the checks above; anything else numeric and unknown is
# reported so a new field cannot slip through unnoticed.
CHECKED_FIELDS = set(MAGNITUDE_RULES) | {"aRms", "vRms", "wattP", "energy",
                                         "masterOn", "psmode", "level",
                                         "modeType", "on", "isDaySensor",
                                         "isDayEnvTarget", "acOnly"}


class Audit:
    def __init__(self, verbose=False):
        self.verbose = verbose
        self.checks = 0
        self.failures = []

    def check(self, label, ok, detail=""):
        self.checks += 1
        if ok:
            if self.verbose:
                print("  ok   " + label + " " + str(detail))
            return True
        self.failures.append((label, detail))
        print("  FAIL " + label + " -- " + str(detail))
        return False

    def note(self, text):
        if self.verbose:
            print("  ..   " + text)


def svp_kpa(temp_c):
    """Saturation vapour pressure, Tetens equation - same shape HA uses."""
    return 0.6108 * math.exp(17.27 * temp_c / (temp_c + 237.3))


def load_raw_payloads(path):
    """Extract the RAW PAYLOADS JSON object from a report file."""
    with open(path, encoding="utf-8", errors="replace") as handle:
        text = handle.read()
    marker = "RAW PAYLOADS"
    start = text.find(marker)
    if start < 0:
        raise SystemExit(
            "%s: no '%s' section found. Is this a report generated by "
            "marspro.generate_device_report?" % (path, marker)
        )
    start = text.find("{", start)
    if start < 0:
        raise SystemExit("%s: malformed RAW PAYLOADS section." % path)
    try:
        return json.loads(text[start:])
    except ValueError as err:
        raise SystemExit("%s: RAW PAYLOADS is not valid JSON (%s)." % (path, err))


def audit_outlet(audit, outlet):
    voltage = outlet.get("vRms")
    current_raw = outlet.get("aRms")
    power = outlet.get("wattP")

    if None not in (voltage, current_raw, power) and voltage:
        amps = current_raw / A_RMS_DIVISOR
        # What the value would mean if the raw number were already in amps: the
        # alternative hypothesis the check has to rule out.
        pf_without_scaling = (power / (voltage * current_raw)
                              if current_raw else None)
        if power >= PF_MIN_POWER_W and amps >= PF_MIN_CURRENT_A:
            pf = power / (voltage * amps)
            audit.note("outlet: %s V, aRms=%s -> %s A, %s W, PF=%.3f "
                       "(PF without scaling would be %s)"
                       % (voltage, current_raw, round(amps, 3), power, pf,
                          "%.3f" % pf_without_scaling
                          if pf_without_scaling is not None else "n/a"))
            audit.check(
                "outlet power factor is physical (V x I vs P)",
                MIN_PF <= pf <= MAX_PF,
                "PF=%.3f with aRms/%d, PF=%.3f if aRms were already amps "
                "(aRms=%s, vRms=%s, wattP=%s)"
                % (pf, int(A_RMS_DIVISOR),
                   pf_without_scaling if pf_without_scaling is not None else -1,
                   current_raw, voltage, power),
            )
        else:
            audit.note("outlet: load too low for a power-factor check "
                       "(%s W, %s A) - skipped" % (power, round(amps, 3)))

        audit.check(
            "current within a plausible range",
            0 <= current_raw <= 100 * MAX_PLAUSIBLE_A,
            current_raw,
        )

    energy = outlet.get("energy")
    if energy is not None:
        kwh = energy / ENERGY_DIVISOR
        audit.note("energy: %s Wh -> %s kWh" % (energy, round(kwh, 3)))
        audit.check("energy magnitude plausible", 0 <= kwh <= 20000, kwh)


def audit_climate(audit, sensor):
    temp, rh, vpd = sensor.get("temp"), sensor.get("humi"), sensor.get("vpd")
    if None not in (temp, rh, vpd):
        expected = svp_kpa(temp) * (1 - rh / 100.0)
        audit.note("T=%s C RH=%s %% -> VPD expected %.3f, reported %s"
                   % (temp, rh, expected, vpd))
        audit.check(
            "VPD consistent with temperature and humidity",
            abs(expected - vpd) <= VPD_TOLERANCE,
            "expected %.3f, reported %s" % (expected, vpd),
        )

    for field, (low, high, unit) in MAGNITUDE_RULES.items():
        value = sensor.get(field)
        if value is None:
            continue
        audit.check("%s within a plausible range" % field,
                    low <= value <= high, "%s %s" % (value, unit))

    for key, value in sensor.items():
        if isinstance(value, (int, float)) and not isinstance(value, bool):
            if key not in CHECKED_FIELDS:
                audit.note("no rule for field %r (value %r) - check it manually"
                           % (key, value))

    for probe in sensor.get("sensors") or []:
        if not isinstance(probe, dict):
            continue
        for field, (low, high, unit) in MAGNITUDE_RULES.items():
            value = probe.get(field)
            if value is None:
                continue
            audit.check("probe %s %s within a plausible range"
                        % (probe.get("id"), field),
                        low <= value <= high, "%s %s" % (value, unit))


def audit_device(audit, serial, device):
    replies = (device or {}).get("replies") or {}
    data = ((replies.get("getDevSta") or {}).get("data")) or {}
    if not data:
        audit.note("%s: no getDevSta payload, skipped" % serial)
        return
    print("- %s" % serial)
    if isinstance(data.get("outlet"), dict):
        audit_outlet(audit, data["outlet"])
    if isinstance(data.get("sensor"), dict):
        audit_climate(audit, data["sensor"])
    for block, payload in data.items():
        if block in ("outlet", "sensor") or not isinstance(payload, dict):
            continue
        # Actuator blocks carry no quantity we can cross-check, but their raw
        # numbers are listed in verbose mode so a surprise is visible.
        audit.note("%s: %s" % (block, json.dumps(payload, sort_keys=True)))


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Cross-check the numeric fields of a Mars Pro device report "
                    "against a second physical quantity (power factor, VPD, "
                    "magnitudes)."
    )
    parser.add_argument("report", help="report file (marspro_device_report.txt)")
    parser.add_argument("-v", "--verbose", action="store_true",
                        help="print every check, including the ones that pass")
    args = parser.parse_args(argv)

    devices = load_raw_payloads(args.report)
    audit = Audit(verbose=args.verbose)
    print("Auditing %s (%d device(s))" % (args.report, len(devices)))
    for serial, device in sorted(devices.items()):
        audit_device(audit, serial, device)

    print()
    if audit.failures:
        print("%d check(s), %d FAILURE(S):" % (audit.checks, len(audit.failures)))
        for label, detail in audit.failures:
            print("  - %s (%s)" % (label, detail))
        print("\nA failure here means the value the integration exposes for that "
              "field is probably wrong: fix the mapping, not the report.")
        return 1
    print("%d check(s), no failure." % audit.checks)
    return 0


if __name__ == "__main__":
    sys.exit(main())
